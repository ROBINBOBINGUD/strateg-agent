# ---------------------------------------------------------------- модель
def saved_pm(i, elig=None, prevent=None, relcut=None):
    """Спасённых номеров в месяц (формула v6, только подходящие группы и перебои из-за исчерпания доли)."""
    elig = FAM_ELIGIBLE[i] if elig is None else elig
    prevent = FAM_PREVENT[i] if prevent is None else prevent
    relcut = FAM_RELCUT[i] if relcut is None else relcut
    return (FAM_GROUPS_AVG[i] * elig * FAM_SIZE[i] * FAM_DISRUPT[i] * EXHAUST_SHARE[i]
            * prevent * FAM_CHURN[i] * relcut)


def ret_year(i, m, **kw):
    """Доп. номеро-месяцы удержания за плановый год: s × m(m+1)/2 (верхняя граница v6: спасённый не уходит до конца года)."""
    return saved_pm(i, **kw) * m * (m + 1) / 2


def ret_3y(i, m, **kw):
    """Доп. номеро-месяцы за плановый год + 24 мес. Спасённый номер платит с выживаемостью (1 - отток) в месяц (допущение v7)."""
    s = saved_pm(i, **kw)
    d = 1 - FAM_CHURN[i]
    n = m + V7_HORIZON_EXTRA_MONTHS
    total = 0.0
    for j in range(1, n + 1):
        length = n - j + 1                     # месяцев от месяца спасения до конца горизонта
        total += (1 - d ** length) / (1 - d)
    return s * total


def invest_parts(i, cost=None):
    cost = COST_PM[i] if cost is None else cost
    return B["dev_pm"][i] * cost, DA_PM[i] * cost


def invest_b(i, cost=None):
    a, b = invest_parts(i, cost)
    return a + b


def accept_groups(i):
    m = B["months"][i]
    return GROUP_CREATED_H2[i] * B["accept_up"][i] * min(m, 6) / 6


def a_calc(i):
    """(а) приглашение без скидки внутри B: новые номера = принятые группы × (размер − 1) × доля новых."""
    new = accept_groups(i) * (FAM_SIZE[i] - 1) * NEW_SHARE_A[i]
    months = new * NEW_MONTHS
    return dict(new=new, months=months, contrib=months * RATE / 1e6)


def e_cohorts(i):
    """(б) тест E со скидкой с 3-го квартала. Месяцы t=1..6 = июль..декабрь. Номер, пришедший в месяце t, платит в году 7-t месяцев."""
    rows = []
    for t in range(1, 7):
        inten = V7_TEST_SHARE if t <= 3 else 1.0
        groups = E["extra_groups"][i] / 6 * inten
        new = groups * E["new_per_group"][i]
        rows.append((t, groups, new))
    return rows


def e_calc(i):
    groups = new = months = disc_year = disc_tail = 0.0
    for t, g, n in e_cohorts(i):
        paid = 7 - t
        groups += g
        new += n
        months += n * paid
        disc_in = min(DISC_MONTHS, paid)
        disc_year += n * disc_in * E["disc_rub"][i]
        disc_tail += n * (DISC_MONTHS - disc_in) * E["disc_rub"][i]
    gross = months * RATE / 1e6
    return dict(groups=groups, new=new, months=months, gross=gross, disc=disc_year / 1e6, tail=disc_tail / 1e6,
                contrib=gross - disc_year / 1e6, invest=E["dev_pm"][i] * COST_PM[i])


def invest_by_quarter(i, with_e=False):
    dev = B["dev_pm"][i]
    q = [0.0, min(dev, V7_DEV_Q2_CAP), max(dev - V7_DEV_Q2_CAP, 0.0), 0.0]
    for k in range(4):
        q[k] += DA_PM[i] / V7_DA_QUARTERS
    q = [x * COST_PM[i] for x in q]
    if with_e:
        ed = E["dev_pm"][i] * COST_PM[i]
        q[1] += ed * V7_E_DEV_SPLIT[0]
        q[2] += ed * V7_E_DEV_SPLIT[1]
    return q


def quarter_k(m, quarter):
    """Месяцев действия B к концу квартала (1..4): действие в последних m месяцах года."""
    return max(0, min(m, 3 * quarter - (12 - m)))


def cum_ret(i, quarter):
    k = quarter_k(B["months"][i], quarter)
    return saved_pm(i) * k * (k + 1) / 2 * RATE / 1e6


def cum_a(i, quarter):
    m = B["months"][i]
    k = quarter_k(m, quarter)
    if m == 0:
        return 0.0
    return a_calc(i)["contrib"] * (k * (k + 1) / 2) / (m * (m + 1) / 2)


def cum_e(i, quarter):
    u = 3 * quarter - 6                       # прошло месяцев с начала июля
    if u <= 0:
        return 0.0
    total = 0.0
    for t, g, n in e_cohorts(i):
        if t > u:
            continue
        paid = u - t + 1
        total += n * paid * RATE / 1e6 - n * min(DISC_MONTHS, paid) * E["disc_rub"][i] / 1e6
    return total


def indicators(i, with_a=False, with_e=False):
    ag = accept_groups(i)
    conn = CONN_BASE + ag + (e_calc(i)["groups"] if with_e else 0)
    active = conn * (ACTIVE_SHARE_BASE + B["act_up"][i] * FAM_ELIGIBLE[i])
    activ = (ACCEPT_BASE + B["accept_up"][i]) * (ACT14_BASE + B["act14_up"][i]) + (E["activ_up"][i] if with_e else 0)
    contrib = ret_year(i, B["months"][i]) * RATE / 1e6
    if with_a:
        contrib += a_calc(i)["contrib"]
    if with_e:
        contrib += e_calc(i)["contrib"]
    return dict(profit=PROFIT_BASE + contrib, active=active, conn=conn, own=OWN_BASE, activ=activ, contrib=contrib)


