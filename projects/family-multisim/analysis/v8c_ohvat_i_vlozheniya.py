"""v8c: правки после критики шага final.

1) Вложения B при полном составе работ: разработка, тестирование, работа команды системы расчётов,
   дизайнер и аналитик по 0,5 ставки на весь год; запрос по этапам (1-й квартал отдельно).
2) Пять показателей планового года с учётом охвата пилота: до решения о расширении сигнал и новый экран
   приглашения получает только половина групп (распределение 1:1), после расширения — 90 % (10 % — группа сравнения).

Запуск: python projects/family-multisim/analysis/v8c_ohvat_i_vlozheniya.py
Результат печатается и сохраняется в analysis/v8c_ohvat_i_vlozheniya.md. Только стандартная библиотека.
Эффекты при полном охвате взяты из v7 (E-047, E-049) и масштабируются линейно по доле охвата (допущение).
"""
import sys
from pathlib import Path

if sys.platform == "win32":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")

SCEN = ("осторожное", "основное", "сильное")

# ---------------------------------------------------------------- 1. Вложения (все — допущения, кроме E-013)
COST_PM = (0.60, 0.45, 0.30)     # v6/v7: млн руб. за чм (осторожное = дороже)
DEV_PM = (3.5, 2.5, 2.0)         # продуктовая стратегия: разработка 2–3,5 чм, основное 2,5
TEST_PM = (1.0, 1.0, 1.0)        # E-013: 1 чм тестирования (не подтверждён)
BILLING_PM = (1.5, 1.0, 0.5)     # допущение: событие об ограничении, статус операции, защита от повтора в системе расчётов
DA_PM_YEAR = 0.5 * 2 * 12        # E-013: дизайнер и аналитик по 0,5 ставки, 12 месяцев = 12 чм
DA_PM_Q1 = 0.5 * 2 * 3           # первый квартал: 3 чм
EXPORT_PM_Q1 = (0.5, 0.25, 0.25) # допущение: выгрузка ограничений и замеры задержки силами системы расчётов в 1-м кв.

# ---------------------------------------------------------------- 2. Эффекты B при полном охвате (v7, E-049, E-047)
# (осторожное, основное, сильное); сильное для показателей в E-049 не приводилось — берём только осторожное и основное
FULL = {
    "profit": (0.0001, 0.009),   # млн руб. за год
    "active": (51, 240),         # активные группы, последний месяц
    "conn": (30, 150),           # подключённые группы, конец года
    "activ": (2.2, 6.5),         # п.п. активации за 14 дней, группы последнего квартала
}
BASE = {"profit": 279.0, "active": 5000, "conn": 8000, "activ": 45.0}   # E-002, E-004, E-006, E-010
GOAL = {"profit": 285.0, "active": 8000, "conn": 12000, "activ": 60.0}

# Охват (доля групп, получающих B) — допущения по календарю пилота (E-041, E-053, E-055)
PILOT, EXPANDED = 0.5, 0.9
COVER = {
    # «Только пилот»: расширения в плановом году нет (результат неясен или отрицателен)
    "только пилот": dict(profit=PILOT, active=PILOT, conn=PILOT, activ=PILOT),
    # «Расширение»: сигнал — с начала 4-го кв. (решение в конце 3-го); экран приглашения — со 2-го месяца 4-го кв.
    "расширение в 4-м кв.": dict(
        profit=(PILOT + EXPANDED) / 2,                 # сигнал: 3-й кв. 0,5, 4-й кв. 0,9; среднее за 2-е полугодие
        active=EXPANDED,                              # последний месяц года
        conn=(PILOT + (PILOT + 2 * EXPANDED) / 3) / 2, # экран приглашения: 3-й кв. 0,5, 4-й кв. (0,5 + 0,9 + 0,9) / 3
        activ=(PILOT + 2 * EXPANDED) / 3,              # группы, созданные в 4-м кв.
    ),
}


def f(x, d=1):
    return f"{x:,.{d}f}".replace(",", " ").replace(".", ",")


OUT = []


def emit(s=""):
    print(s)
    OUT.append(s)


def table(head, rows):
    emit("| " + " | ".join(head) + " |")
    emit("|" + "---|" * len(head))
    for r in rows:
        emit("| " + " | ".join(str(c) for c in r) + " |")
    emit()


emit("# v8c. Вложения при полном составе работ и пять показателей с учётом охвата пилота")
emit()
emit("## Таблица 1. Вложения B, млн руб.")
emit()
emit("Формула: (разработка + тестирование + система расчётов + дизайнер и аналитик) × цена чм. "
     f"Дизайнер и аналитик — по 0,5 ставки на 12 месяцев = {f(DA_PM_YEAR, 0)} чм [E-013].")
emit()
rows = []
for i, sc in enumerate(SCEN):
    pm_total = DEV_PM[i] + TEST_PM[i] + BILLING_PM[i] + DA_PM_YEAR
    pm_no_da = DEV_PM[i] + TEST_PM[i] + BILLING_PM[i]
    q1 = (DA_PM_Q1 + EXPORT_PM_Q1[i]) * COST_PM[i]
    total = pm_total * COST_PM[i]
    rows.append([sc, f(COST_PM[i], 2), f(DEV_PM[i]), f(TEST_PM[i]), f(BILLING_PM[i]), f(DA_PM_YEAR, 0),
                 f(pm_total), f(total, 2), f(pm_no_da * COST_PM[i], 2), f(q1, 2), f(total - q1, 2)])
table(["Сценарий", "Цена чм", "Разработка, чм", "Тестирование, чм", "Система расчётов, чм", "Дизайнер и аналитик, чм",
       "Всего, чм", "Вложения всего", "Без дизайнера и аналитика", "Этап 1-го кв.", "Этап 2–4-го кв."], rows)

emit("Сравнение с v7: там вложения основного сценария 3,4 млн руб. (7,5 чм: разработка с тестированием 3,0 и дизайнер "
     "с аналитиком 4,5) [E-047]. Вклад B в прибыль 0,009 млн руб. [E-047] не меняется; вывод «не окупается» сохраняется.")
emit()

emit("## Таблица 2. Пять показателей планового года с учётом охвата")
emit()
emit("Прирост к «без изменений» = прирост v7 при полном охвате × доля охвата. Владельцы — 1 000 во всех строках [E-049].")
emit()
rows = []
for j, sc in ((1, "основное"), (0, "осторожное")):
    rows.append([sc, "полный охват (v7)", f(BASE["profit"] + FULL["profit"][j], 3), f(BASE["active"] + FULL["active"][j], 0),
                 f(BASE["conn"] + FULL["conn"][j], 0), f(BASE["activ"] + FULL["activ"][j], 1) + " %"])
    for name, c in COVER.items():
        rows.append([sc, name,
                     f(BASE["profit"] + FULL["profit"][j] * c["profit"], 3),
                     f(BASE["active"] + FULL["active"][j] * c["active"], 0),
                     f(BASE["conn"] + FULL["conn"][j] * c["conn"], 0),
                     f(BASE["activ"] + FULL["activ"][j] * c["activ"], 1) + " %"])
rows.append(["—", "без изменений", f(BASE["profit"], 3), f(BASE["active"], 0), f(BASE["conn"], 0), f(BASE["activ"], 1) + " %"])
rows.append(["—", "цель", f(GOAL["profit"], 1), f(GOAL["active"], 0), f(GOAL["conn"], 0), f(GOAL["activ"], 0) + " %"])
table(["Сценарий эффекта", "Охват", "Прибыль, млн руб.", "Активные (посл. месяц)", "Подключённые (конец года)",
       "Активация за 14 дней (4-й кв.)"], rows)

emit("## Таблица 3. Разрыв до цели (основное, расширение в 4-м кв.)")
emit()
c = COVER["расширение в 4-м кв."]
gap = {k: GOAL[k] - (BASE[k] + FULL[k][1] * c[k]) for k in BASE}
table(["Прибыль, млн руб.", "Активные", "Подключённые", "Активация, п.п."],
      [[f(gap["profit"], 2), f(gap["active"], 0), f(gap["conn"], 0), f(gap["activ"], 1)]])

emit("Доли охвата: " + "; ".join(f"{k}: " + ", ".join(f"{m} {f(v * 100, 0)} %" for m, v in c.items())
                                  for k, c in COVER.items()) + ".")
Path(__file__).with_suffix(".md").write_text("\n".join(OUT) + "\n", encoding="utf-8")
print(f"Сохранено: {Path(__file__).with_suffix('.md')}")
