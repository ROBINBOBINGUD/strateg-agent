nd = NormalDist()
za, zb = nd.inv_cdf(1 - ALPHA / 2), nd.inv_cdf(POWER)


def n_arm(p1, p2):
    pb = (p1 + p2) / 2
    return ceil((za * sqrt(2 * pb * (1 - pb)) + zb * sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2 / (p1 - p2) ** 2)


def mde(n, p1):
    """Наибольшая цель p2<p1 (наименьшее улучшение), обнаруживаемая при n на вариант (поиск делением пополам).
    n_arm растёт при приближении p2 к p1: если для mid нужно больше n, mid слишком близко к p1 — сдвигаем верхнюю границу."""
    lo, hi = 0.0001, p1 - 1e-6
    for _ in range(100):
        mid = (lo + hi) / 2
        if n_arm(p1, mid) > n:
            hi = mid
        else:
            lo = mid
    return lo


