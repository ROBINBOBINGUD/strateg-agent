NORM = NormalDist()
ZA = NORM.inv_cdf(1 - ALPHA / 2)


def zb(power):
    return NORM.inv_cdf(power)


def n_arm(p1, p2, power=0.8):
    """Групп на вариант для сравнения двух долей (формула как в v6)."""
    pb = (p1 + p2) / 2
    return ceil((ZA * sqrt(2 * pb * (1 - pb)) + zb(power) * sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2 / (p1 - p2) ** 2)


def mde_down(n, p1, power=0.8):
    """Наименьшее обнаружимое снижение (доля): p1 - p2 при n на вариант; None, если не обнаружимо даже при p2 -> 0."""
    if n < 1 or n_arm(p1, 1e-4, power) > n:
        return None
    lo, hi = 1e-4, p1 - 1e-6
    for _ in range(100):
        mid = (lo + hi) / 2
        if n_arm(p1, mid, power) > n:
            hi = mid
        else:
            lo = mid
    return p1 - lo


def mde_up(n, p1, power=0.8):
    """Наименьший обнаружимый рост (доля): p2 - p1; None, если не обнаружим даже при p2 -> 1."""
    if n < 1 or n_arm(p1, 1 - 1e-4, power) > n:
        return None
    lo, hi = p1 + 1e-6, 1 - 1e-4
    for _ in range(100):
        mid = (lo + hi) / 2
        if n_arm(p1, mid, power) > n:
            lo = mid
        else:
            hi = mid
    return hi - p1


# ---------------------------------------------------------------- поток и пул
def flow_week(i):
    """Линейный поток подходящих групп с первым событием и свободным остатком, групп в неделю."""
    return FAM_GROUPS_AVG[i] * FAM_WEEK_EVENT[i] * FAM_ELIGIBLE[i] * FREE_SHARE[i]


def pool(i):
    """Пул подходящих групп (конечный: группа входит один раз)."""
    return FAM_GROUPS_AVG[i] * FAM_ELIGIBLE[i]


def hazard(i):
    """Недельная доля оставшегося пула, дающая первое подходящее событие (= flow / pool)."""
    return FAM_WEEK_EVENT[i] * FREE_SHARE[i]


def cum_groups(i, weeks):
    """Накопленное число вошедших групп за weeks недель набора с учётом исчерпания пула."""
    return pool(i) * (1 - (1 - hazard(i)) ** weeks)


def arm_n(i, weeks):
    return int(cum_groups(i, weeks) / 2)


def weeks_needed(i, n):
    """Недель набора, чтобы набрать n на вариант (2n групп); None, если пул не даёт 2n за MAX_WEEKS."""
    for w in range(1, MAX_WEEKS + 1):
        if cum_groups(i, w) >= 2 * n:
            return w
    return None


