# ---------------------------------------------------------------- 5. показатель работы услуги
def cp_upper_1err(n, conf=0.95):
    """Односторонняя верхняя граница Клоппера — Пирсона при 1 ошибке из n: P(X<=1 | n, p) = 1 - conf."""
    target = 1 - conf
    lo, hi = 0.0, 1.0
    for _ in range(200):
        mid = (lo + hi) / 2
        cdf = (1 - mid) ** n + n * mid * (1 - mid) ** (n - 1)
        if cdf > target:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


